/** Only fixed interface copy passes through this catalogue; credentials and
 * client identity are rendered directly. Keeping error state as a key allows
 * an already visible validation message to follow a language change. */
export function useTextoAuth() {
  const { idioma } = useIdioma()
  return useCallback((texto: string) => idioma === 'en' ? TEXTOS[texto] ?? texto : texto, [idioma])
}
