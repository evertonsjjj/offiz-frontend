export function useTextoEscritorio() {
  const { idioma } = useIdioma()
  return useCallback((text: string, ...values: unknown[]) => {
    const copy = idioma === 'en' ? TEXTOS_ESCRITORIOS[text] ?? text : text
    return values.length ? copy.replace(/\{(\d+)\}/g, (match, index: string) => Number(index) < values.length ? String(values[Number(index)] ?? '') : match) : copy
  }, [idioma])
}
