export function traduzirInicio(texto: string, idioma: 'pt-BR' | 'en'): string {
  return idioma === 'en' ? TEXTOS_INICIO[texto] ?? texto : texto
}

export function useTextoInicio() {
  const { idioma } = useIdioma()
  const texto = useCallback((valor: string) => traduzirInicio(valor, idioma), [idioma])
  return { idioma, texto }
}

export function localizarInicio(inicio: InicioOrganizacao, idioma: 'pt-BR' | 'en'): InicioOrganizacao {
  if (idioma !== 'en') return inicio
  const texto = (valor: string) => traduzirInicio(valor, idioma)
  const localizar = (s: SolucaoInicio): SolucaoInicio => {
    const curada = s.origem !== 'aprendida' && (s.id.startsWith('capacidade:') || s.rotulo_curado === true)
    return {
      ...s,
      // Títulos/pedidos aprendidos e modelos personalizados são dados do cliente.
      ...(curada ? { titulo: texto(s.titulo), descricao: texto(s.descricao), prompt: texto(s.prompt) } : {}),
      entrega: texto(s.entrega), etapas: s.etapas.map(texto), insumos: s.insumos.map(texto),
      motivo: s.origem === 'aprendida' ? s.motivo : s.motivo ? texto(s.motivo) : undefined,
    }
  }
  const solucoes = inicio.solucoes.map(localizar)
  return {
    ...inicio, solucoes, outras_solucoes: inicio.outras_solucoes.map(localizar),
    solucoes_ocultas: inicio.solucoes_ocultas?.map(localizar),
    sabatina: { ...inicio.sabatina, pergunta: texto(inicio.sabatina.pergunta), opcoes: inicio.sabatina.opcoes.map((opcao) => {
      const solucao = solucoes.find((s) => s.id === opcao.id)
      return solucao ? { ...opcao, label: solucao.titulo, prompt: solucao.prompt } : opcao.id === 'conhecer-empresa' ? { ...opcao, label: texto(opcao.label), prompt: texto(opcao.prompt) } : opcao
    }) },
  }
}
